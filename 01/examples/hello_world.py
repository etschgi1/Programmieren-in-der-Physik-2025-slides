# Printing to the console
print("Hello, world!")

# Variables and data types
name = "Alice"  # String
age = 30        # Integer
height = 175.5    # Float
stud_b = True  # Boolean

# Printing variables
print("Name:", name) # Name: Alice
print("Age:", age) # Age: 30
print("Height:", height) # Height: 175.5
print("Student?:", stud_b) # Student?: True

# Basic arithmetic operations
sum_ = age + 5
difference = height - 1.5
product = age * 2
quotient = height / 2

print("Sum:", sum_) # 35
print("Difference:", difference) # 4.0
print("Product:", product) # 60 
print("Quotient:", quotient) # 2.75
